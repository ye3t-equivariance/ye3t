"""Reference algebra for exact local source/product images.

Local input maps use the source compiler's real form. Binary products receive
the paired-CG phase before their real-form image is reduced. Complete
tableau/magnetic reconstruction is required for every discarded coordinate.

These helpers currently support reference tests only. Production source counts
come from the canonical fixed-content/role multiplicity decomposition. Do not
make expansion of every hidden feature into these polynomial rows a prerequisite
for representation selection. A primitive/decomposable quotient requires its
own configured operation policy; this module selects a linear image and does
not discard a feature merely because it can be written as a product.

For primitive/decomposable analysis, these exact image operations can support
the decomposable subspace generated by specified admissible child products.
The target multiplicity space, child products and degree/cost grading must be
specified separately. This module alone does not construct the primitive
quotient. Polynomial rows are a computational representation of these maps.
"""

from collections import defaultdict
from functools import lru_cache
from itertools import product

from ye3t.exact_scalars import exact_scalar
from . import lifted_cauchy_scalar as scalar
from .tagged_cauchy_general import _add_exact, _exact_pivot_image


@lru_cache(maxsize=128)
def _real_product_angular(left_L, right_L, target_L):
    """Exact real CG tensor with the established odd-coupling minus-i phase."""
    import sympy as sp
    from sympy.physics.wigner import clebsch_gordan
    left, right, target = (scalar._real_form_matrix(ell) for ell in (left_L, right_L, target_L))
    phase = -sp.I if (left_L+right_L-target_L) % 2 else sp.S.One
    entries = defaultdict(lambda: sp.S.Zero)
    for m in range(-left_L, left_L+1):
        for n in range(-right_L, right_L+1):
            M = m+n
            if abs(M) > target_L:
                continue
            cg = clebsch_gordan(left_L, right_L, target_L, m, n, M)
            if not cg:
                continue
            a = [(i, left[m+left_L, i]) for i in range(left.cols) if left[m+left_L, i]]
            b = [(j, right[n+right_L, j]) for j in range(right.cols) if right[n+right_L, j]]
            c = [(k, sp.conjugate(target[M+target_L, k])) for k in range(target.cols) if target[M+target_L, k]]
            for (i, x), (j, y), (k, z) in product(a, b, c):
                entries[i, j, k] += phase*cg*x*y*z
    result = []
    for key, value in sorted(entries.items()):
        value = sp.expand(value)
        if sp.im(value) != 0:
            raise ArithmeticError("Paired CG phase failed to give a real local product")
        if value:
            result.append((*key, exact_scalar(value)))
    return tuple(result)


def _multiply_rows(left, right):
    result = {}
    for a, x in left.items():
        for b, y in right.items():
            _add_exact(result, tuple(sorted(a+b)), x*y)
    return result


def _product_rows(compiled, left, right):
    """Apply canonical separate Young/angular maps to exact source rows."""
    request = compiled["request"]
    if request["operation"] != "same_action_tensor_product" or compiled["role_scale"] != "1":
        raise ValueError("Local seed images require the same-action tensor product")
    ll, lr = request["left"]["magnetic_count"], request["right"]["magnetic_count"]
    output = compiled["output_layout"]
    angular = _real_product_angular(request["left"]["key"]["rotation_L"],
                                    request["right"]["key"]["rotation_L"], output["key"]["rotation_L"])
    young = defaultdict(list)
    for placement, mode, i, j, t, coefficient in compiled["young"]:
        if placement:
            raise ValueError("Local products require a common physical row domain")
        young[mode].append((i, j, t, exact_scalar(scalar._sympy().sympify(coefficient))))
    result, products = [], {}
    for channel in compiled["channels"]:
        a, b, mode, exchange = (channel[name] for name in ("left_channel", "right_channel", "young_copy", "exchange"))
        components = [{} for _ in range(output["tableau_count"]*output["magnetic_count"])]
        terms = [(a, b, exact_scalar(1))]
        if exchange and a != b:
            weight = exact_scalar(scalar._sympy().sqrt(2)/2)
            terms = [(a, b, weight), (b, a, exchange*weight)]
        for ca, cb, weight in terms:
            for i, j, t, y in young[mode]:
                for m, n, M, cg in angular:
                    key = ca, cb, i*ll+m, j*lr+n
                    if key not in products:
                        products[key] = _multiply_rows(left[ca][i*ll+m], right[cb][j*lr+n])
                    for monomial, coefficient in products[key].items():
                        _add_exact(components[t*output["magnetic_count"]+M], monomial, coefficient*y*cg*weight)
        result.append(tuple(components))
    return tuple(result)


def _independent_multiplets(rows):
    """Stable source-first pivots with exact reconstruction on every component."""
    if not rows:
        return (), ()
    components = len(rows[0])
    if any(len(row) != components for row in rows):
        raise ValueError("An image reduction must use one complete irreducible carrier")
    selected, reconstruction = _exact_pivot_image([row[0] for row in rows])
    for index, coordinates in enumerate(reconstruction):
        for component in range(components):
            actual = {}
            for pivot, coefficient in coordinates.items():
                for monomial, value in rows[selected[pivot]][component].items():
                    _add_exact(actual, monomial, coefficient*value)
            if actual != rows[index][component]:
                raise ArithmeticError("Local image reconstruction differs across tableau/magnetic components")
    return selected, reconstruction


def _tagged_source_polynomials(report):
    """Lift compiler-owned source coordinates into common real input variables."""
    from .tagged_cauchy_carriers import _source_rows
    requests = {coordinate: record["request"] for record in report["selected_records"]
                for coordinate in record["request"]["selected_coordinates"]}
    labels = {item["label"]["coordinate_id"]: item["label"] for item in report["available_coordinate_inventory"]}
    by_id = {}
    for coordinate, request in requests.items():
        channels = request["channels"]
        raw = _source_rows(request, labels[coordinate])
        components = []
        for row in raw:
            converted = {}
            for monomial, coefficient in row.items():
                factors = []
                for channel_index, role, magnetic in monomial:
                    channel = channels[channel_index]
                    factors.append((role, channel["neighbor_species"], int(channel["radial_channel"]),
                                    int(channel["l"]), channel["source_family_id"], magnetic))
                _add_exact(converted, tuple(sorted(factors)), coefficient)
            components.append(converted)
        by_id[coordinate] = tuple(components)
    return {row["id"]: tuple(by_id[coordinate] for coordinate in row["coordinate_ids"])
            for row in report["graph_inventory"]}


def _physical_tag_rows(components, tag_count):
    """Reduce same-occurrence products; keep inclusive moments as variables."""
    from .tagged_cauchy_carriers import _physical_real_edge_product
    output = []
    for row in components:
        reduced = {}
        for monomial, coefficient in row.items():
            tags = [[] for _ in range(tag_count)]
            density = []
            for factor in monomial:
                role, *source = factor
                if role == tag_count:
                    density.append(("density", *source))
                elif 0 <= role < tag_count:
                    tags[role].append(tuple(source))
                else:
                    raise ValueError("Polynomial role is outside the physical tag domain")
            expanded = {tuple(sorted(density)): coefficient}
            for role, factors in enumerate(tags):
                if not factors:
                    raise ValueError("A retained physical tag must occur in each local source monomial")
                replacement = _physical_real_edge_product(tuple(sorted(factors)))
                updated = {}
                for previous, value in expanded.items():
                    for source, weight in replacement.items():
                        # A uniform sortable key retains the tag identity and
                        # the exact radial/angular physical product coordinate.
                        key = tuple(sorted((*previous, ("tag", role, *source))))
                        _add_exact(updated, key, value*weight)
                expanded = updated
            for key, value in expanded.items():
                _add_exact(reduced, key, value)
        output.append(reduced)
    return tuple(output)
